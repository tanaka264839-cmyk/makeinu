# 字として数えられるのに何も見えない字（ハングルの空き字・点字の空白など）
_何も見えない字 = frozenset("\u3164\u115f\u1160\uffa0\u2800\u17b4\u17b5\u180e")


@dataclass(frozen=True)
class 板:
    鍵: str
    名前: str
    ひとこと: str


@dataclass(frozen=True)
class 相談先:
    名前: str
    番号: str
    ひとこと: str


def _行を読む(ファイル名):
    with open(os.path.join(中身の場所, ファイル名), encoding="utf-8") as f:
        for 行 in f:
            行 = 行.rstrip("\r\n")
            if 行.strip() and not 行.startswith("#"):
                yield 行


def 板の一覧を読む():
    return [板(*行.split("\t")[:3]) for 行 in _行を読む("板の一覧.txt")]


def 相談先を読む():
    return [相談先(*行.split("\t")[:3]) for 行 in _行を読む("相談先.txt")]


def 文を読む(ファイル名):
    """中身/ の文をそのまま読む（利用の決まり・個人情報の扱い）。直せば、起動し直さずに画面に出る。"""
    with open(os.path.join(中身の場所, ファイル名), encoding="utf-8") as f:
        return f.read()


def 言葉を読む(ファイル名):
    return [そろえる(行) for 行 in _行を読む(ファイル名)]


def そろえる(文):
    """比べるためだけの形。全角半角・片仮名・空白・大文字小文字の違いを消す（書き方の違いで守りをすり抜けさせない）。"""
    文 = unicodedata.normalize("NFKC", 文).lower()
    文 = "".join(chr(ord(字) - 0x60) if "ァ" <= 字 <= "ヶ" else 字 for 字 in 文)
    return re.sub(r"\s+", "", 文)


def 見張る形(文):
    """止める言葉・相談先の言葉・聞き役に似た名乗りと比べるためだけの形。そろえる に加えて、見えない字と記号も外す
    （「死・ね」や、字の間に見えない字を挟んでも見分けるため）。同じ名乗りかの判定には使わない（「元・店長」と「元店長」は別の名乗り）。"""
    return "".join(字 for 字 in そろえる(文) if 字 not in _何も見えない字 and unicodedata.category(字)[0] not in "CMPSZ")


def 見える字があるか(文):
    """記号や絵文字は見えるので数える（「……」だけの吐き出しも置ける）。"""
    return any(字 not in _何も見えない字 and unicodedata.category(字) not in ("Cc", "Cf", "Mn", "Me", "Zs", "Zl", "Zp") for 字 in 文)


def 本文を整える(文):
    """保存する形。改行はそろえ、見えない制御文字と残さない字は落とし、前後の空白（全角も）を外す。"""
    文 = (文 or "").replace("\r\n", "\n").replace("\r", "\n")
    文 = "".join(字 for 字 in 文 if (字 == "\n" or unicodedata.category(字) != "Cc") and 字 not in _残さない字)
    return 文.strip()


def 名乗りを整える(文):
    """名乗りは1行。改行や続く空白は1つの空白にまとめる。"""
    return re.sub(r"\s+", " ", 本文を整える(文))


@dataclass(frozen=True)
class 見立て:
    通す: bool
    断る訳: str = ""
    相談先を出す: bool = False


def 書き込みを見立てる(本文, 止める言葉, 相談先の言葉, 上限=本文の上限):
    """本文は整えた後のもの。人を叩く言葉は止め、つらすぎる言葉は通したうえで相談先を出す。"""
    if not 本文 or not 見える字があるか(本文):
        return 見立て(False, "何か書いてから送ってください。")
    if len(本文) > 上限:
        return 見立て(False, f"{上限}字までです。いまは{len(本文)}字あります。")
    比べる形 = 見張る形(本文)
    if _どれかが入っている(止める言葉, 比べる形):
        return 見立て(False, "人を傷つける言葉が入っています。ここは誰も叩かない場所です。言い方を変えて書いてください。")
    return 見立て(True, 相談先を出す=_どれかが入っている(相談先の言葉, 比べる形))


def _どれかが入っている(言葉たち, 比べる形):
    return any(見張る形(言葉) and 見張る形(言葉) in 比べる形 for 言葉 in 言葉たち)


def 見立てる(文, 上限=本文の上限):
    """中身/ の言葉の一覧を読んで見立てる（一覧を直せば、起動し直さずに効く）。"""
    return 書き込みを見立てる(文, 言葉を読む("止める言葉.txt"), 言葉を読む("相談先の言葉.txt"), 上限)


def 知らせを見立てる(本文, 書き込みを選んだ, 上限=本文の上限):
    """持ち主への知らせ。本文は整えた後のもの。ひどい書き込みを書き写して知らせられるよう、止める言葉は効かせない。
    書き込みを選んで知らせる時は、理由を書かなくてもよい。つらすぎる言葉には、書き込みと同じく相談先を出す。"""
    if not 見える字があるか(本文) and not 書き込みを選んだ:
        return 見立て(False, "何を知らせたいか書いてから送ってください。")
    if len(本文) > 上限:
        return 見立て(False, f"{上限}字までです。いまは{len(本文)}字あります。")
    return 見立て(True, 相談先を出す=_どれかが入っている(言葉を読む("相談先の言葉.txt"), 見張る形(本文)))


def 名乗りを見立てる(名乗り):
    """名乗りは整えた後のもの。守りと20字までに加え、聞き役に似た名乗りと「（AI）」の付く名乗りは使わせない（AIの返事と見分けられなくなるため）。"""
    if _どれかが入っている(聞き役に似た名乗り, 見張る形(名乗り)) or "(ai)" in そろえる(名乗り):
        return 見立て(False, "「聞き役」は、AIの聞き役の返事に付く名乗りなので使えません。")
    return 見立てる(名乗り, 名乗りの上限)


def 聞き役の返事を出せるか(返事):
    """AIの聞き役の文も、人の書き込みと同じ守りを通す。返事は整えた後のもの。止める言葉に加え、つらすぎる言葉・
    外への道・聞き役が使わない言葉（励まし、負けを問う言葉、AIの断りの文）が入っていたり、長すぎたりすれば出さない。
    かなの無い文も出さない（AIが断る時は英語で返すことがある。つらい話を書いた人に、断りの英語を見せないため）。"""
    見立て = 見立てる(返事, 聞き役の返事の上限)
    比べる形 = そろえる(返事)
    return (見立て.通す and not 見立て.相談先を出す and re.search("[ぁ-ん]", 比べる形) and "://" not in 比べる形 and "www." not in 比べる形
            and not any(言葉 and 言葉 in 比べる形 for 言葉 in 言葉を読む("聞き役が使わない言葉.txt")))


def 聞き役への頼みを読む():
    """AIに最初に渡す頼みの文。# で始まる行と空の行は渡さない（直せば、次に返す時から効く）。"""
    return "\n".join(_行を読む("聞き役への頼み.txt"))


def 今夜の始まり(日本の時刻):
    """夜の部屋が開いていれば、今夜が始まった時刻（23時）。閉まっていれば None。
    0時〜5時は、前の日の23時からの続きの夜として扱う（日付の変わり目で部屋が分かれないように）。"""
    if 日本の時刻.hour >= 夜の始まり時:
        日 = 日本の時刻
    elif 日本の時刻.hour < 夜の終わり時:
        日 = 日本の時刻 - timedelta(days=1)
    else:
        return None
    return 日.replace(hour=夜の始まり時, minute=0, second=0, microsecond=0)


def 番号を読む(文):
    """送られてきた字を番号にする。半角の数字で、記録に入る桁までの時だけ。それ以外は無い物として None（²・①・とても長い数字で止まらないように）。"""
    return int(文) if 文 and 文.isascii() and 文.isdigit() and len(文) <= 番号の桁の上限 else None


def _番地(文):
    try:
        return str(ipaddress.ip_address((文 or "").strip()))
    except ValueError:
        return None


def _港(文):
    文 = (文 or "").strip()
    return int(文) if 文.isascii() and 文.isdigit() and 1 <= int(文) <= 65535 else None


def 接続元を決める(じかの番地, じかの港, 見出しの番地, 見出しの港):
    """書いた人の接続元 (番地＝IPアドレス, 港＝発信元ポート番号)。
    前に置く https の受け口は同じサーバーの中から来るので、じかの相手が自分（127.0.0.1 など）の時だけ、
    受け口が見出しに入れた、来た人の番地と港を使う。外から来た相手が付けた見出しは、なりすましになるので使わない。
    開示の求めでは番地と港の組で人を探すので、番地だけ確かな時も番地は残す。"""
    じか = _番地(じかの番地)
    if じか is None or not ipaddress.ip_address(じか).is_loopback:
        return じかの番地, じかの港
    番地 = _番地(見出しの番地)
    if 番地 is None:
        return じかの番地, じかの港
    return 番地, _港(見出しの港)


def 小部屋の置き場(部屋番号):
    return f"{小部屋の頭}{部屋番号}"


def 小部屋の番号(置き場):
    """小部屋の置き場なら部屋番号、ほかは None。"""
    if 置き場 and 置き場.startswith(小部屋の頭) and 置き場[len(小部屋の頭):].isdigit():
        return int(置き場[len(小部屋の頭):])
    return None
