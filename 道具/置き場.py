"""負け犬の癒し：書き込みの置き場（板と、板でない置き場）の名前と画面の場所。"""
import 決まり

# 板の一覧の外にある置き場：名前と画面の場所
板でない置き場 = {
    決まり.勝ちの置き場: ("今日の小さな勝ち", "/kachi"),
    決まり.その後の置き場: ("その後の話の棚", "/sonogo"),
    決まり.宣言の置き場: ("もう一回の宣言", "/mouikkai"),
    決まり.独り言の置き場: ("独り言", "/hitori"),
    決まり.夜の置き場: ("夜の部屋", "/yoru"),
}


def 置き場の名前():
    return {板.鍵: 板.名前 for 板 in 決まり.板の一覧を読む()} | {鍵: 名前 for 鍵, (名前, _) in 板でない置き場.items()}


def 置き場の場所(板の鍵):
    部屋番号 = 決まり.小部屋の番号(板の鍵)
    if 部屋番号:
        return f"/heya/{部屋番号}"
    return 板でない置き場[板の鍵][1] if 板の鍵 in 板でない置き場 else f"/ita/{板の鍵}"


def 置き場を言う(板の鍵, 名前):
    部屋番号 = 決まり.小部屋の番号(板の鍵)
    return f"小部屋#{部屋番号}" if 部屋番号 else 名前.get(板の鍵, 板の鍵)
